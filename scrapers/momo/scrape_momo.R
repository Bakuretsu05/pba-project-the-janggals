#!/usr/bin/env Rscript
if (.Platform$OS.type == "windows" && !isTRUE(l10n_info()[["UTF-8"]]))
  invisible(Sys.setlocale("LC_CTYPE", "English_United States.utf8"))
script <- sub("^--file=", "", grep("^--file=", commandArgs(), value = TRUE)[[1L]])
platform_dir <- dirname(normalizePath(script, winslash = "/", mustWork = TRUE))
root <- dirname(dirname(platform_dir))
if (dir.exists(file.path(root, ".R-library"))) .libPaths(c(file.path(root, ".R-library"), .libPaths()))
if (file.exists(file.path(root, ".Renviron"))) readRenviron(file.path(root, ".Renviron"))
contact <- Sys.getenv("SCRAPER_CONTACT")
if (!nzchar(contact)) stop("SCRAPER_CONTACT must be set in .Renviron or GitHub secrets")
for (pkg in c("httr2", "rvest", "xml2", "jsonlite"))
  if (!requireNamespace(pkg, quietly = TRUE)) stop("Missing package ", pkg, "; run Rscript scrapers/momo/install_dependencies.R")
source(file.path(platform_dir, "momo.R"), encoding = "UTF-8")
args <- commandArgs(trailingOnly = TRUE)
if (length(args) > 1L) stop("Usage: Rscript scrapers/momo/scrape_momo.R [product-table.csv]")
input <- if (length(args)) args[[1L]] else file.path(root, "products", "products.csv")
products <- momo_read_products(input)
result <- momo_collect(products, platform_dir, contact)
quit(status = result$exit_status)
